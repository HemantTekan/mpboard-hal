def tab(head, rows, sums=None, hl=None):
    h = "".join(f"<th>{c}</th>" for c in head)
    body = ""
    for i, r in enumerate(rows):
        cls = " class='hl'" if hl is not None and i == hl else ""
        body += f"<tr{cls}>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>"
    if sums:
        body += "<tr class='sum'>" + "".join(f"<td>{c}</td>" for c in sums) + "</tr>"
    return f"<div class='tw'><table class='st'><thead><tr>{h}</tr></thead><tbody>{body}</tbody></table></div>"


def vtab(h1, h2, a, b):
    rows = "".join(f"<tr><td>{x}</td><td>{y}</td></tr>" for x, y in zip(a, b))
    return f"<div class='tw'><table class='st dt'><thead><tr><th>{h1}</th><th>{h2}</th></tr></thead><tbody>{rows}</tbody></table></div>"


def htab(h1, h2, a, b):
    r1 = f"<tr><td class='lb'>{h1}</td>" + "".join(f"<td>{c}</td>" for c in a) + "</tr>"
