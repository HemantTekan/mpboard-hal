def arc(V, r, a1, a2, c="#c2410c"):
    """angle arc at V from direction a1 to a2 (degrees, counter-clockwise, maths convention)"""
    d = (a2 - a1) % 360
    x1, y1 = V[0] + r * math.cos(math.radians(a1)), V[1] - r * math.sin(math.radians(a1))
    x2, y2 = V[0] + r * math.cos(math.radians(a1 + d)), V[1] - r * math.sin(math.radians(a1 + d))
    return f"<path d='M {x1:.1f} {y1:.1f} A {r} {r} 0 {1 if d > 180 else 0} 0 {x2:.1f} {y2:.1f}' fill='none' stroke='{c}' stroke-width='1.8'/>"


def ra(V, P1, P2, s=11, c=INK):
    """right-angle square at V between VP1 and VP2"""
    def u(P):
        dx, dy = P[0] - V[0], P[1] - V[1]
        L = math.hypot(dx, dy)
        return dx / L, dy / L
    (a, b), (c_, d) = u(P1), u(P2)
    q1 = (V[0] + s * a, V[1] + s * b)
    q2 = (V[0] + s * (a + c_), V[1] + s * (b + d))
    q3 = (V[0] + s * c_, V[1] + s * d)
    return f"<polyline points='{q1[0]:.1f},{q1[1]:.1f} {q2[0]:.1f},{q2[1]:.1f} {q3[0]:.1f},{q3[1]:.1f}' fill='none' stroke='{c}' stroke-width='1.4'/>"


