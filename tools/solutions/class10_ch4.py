def eqs(*pairs):
    """Separate equations, one per row, aligned at '='."""
    rows = "".join(f"<span class='l'>{mcell(a)}</span><span class='s'>=</span><span class='r'>{mcell(b)}</span>" for a, b in pairs)
    return "<div class='eq'>" + rows + "</div>"


def ok(t):
    return f"<p class='ok'>{t}</p>"


def p(t):
    return f"<p>{t}</p>"


def roots_of(a, b, c):
    """Exact rational roots (for asserts) or None."""
    d = b * b - 4 * a * c
    if d < 0:
        return None
    r = math.isqrt(d)
    if r * r != d:
        return None
    return sorted({F(-b + r, 2 * a), F(-b - r, 2 * a)})


