def eqs(*pairs):
    """Separate equations, one per row, aligned at '='."""
    rows = "".join(f"<span class='l'>{mcell(a)}</span><span class='s'>=</span><span class='r'>{mcell(b)}</span>" for a, b in pairs)
    return "<div class='eq'>" + rows + "</div>"


def ok(t):
    return f"<p class='ok'>{t}</p>"


def p(t):
    return f"<p>{t}</p>"


def tag(t, n):
    """Equation with its number, e.g. x + y = 10 ....(1)"""
    l, r = t.split("=")
    return (f"<div class='eq'><span class='l'>{mcell(l.strip())}</span><span class='s'>=</span>"
            f"<span class='r'>{mcell(r.strip())} &nbsp;&nbsp;…({n})</span></div>")


def vtable(name, xs, ys):
    head = "".join(f"<td>{m(str(x))}</td>" for x in xs)
    row = "".join(f"<td>{m(str(y))}</td>" for y in ys)
    return (f"<div class='vt2'><div class='muted'>{name}</div><table class='xy'><tr><th>{m('x')}</th>{head}</tr>"
            f"<tr><th>{m('y')}</th>{row}</tr></table></div>")


def _norm(t):
    return t.replace("+-", "-").replace("--", "+")


def vt(name, ytex, num, den, xs):
    """Work out y for each x from y = num/den, then the table. num uses {x} and \\times."""
    import re as _re
    calc, ys = "", []
    for x in xs:
        xs_ = f"({x})" if x < 0 else str(x)
        sub = num.replace("{x}", xs_)
        prod = _norm(_re.sub(r"(\d+)\\times\{x\}", lambda mm: str(int(mm.group(1)) * x), num).replace("{x}", str(x)))
        nv = eval(num.replace("\\times", "*").replace("{x}", f"({x})"))
        val = F(nv, den)
        assert val.denominator == 1
        ys.append(int(val))
        if den == 1:
            steps = [sub, prod, str(int(val))]
        else:
            steps = [f"\\dfrac{{{sub}}}{{{den}}}", f"\\dfrac{{{prod}}}{{{den}}}", f"\\dfrac{{{nv}}}{{{den}}}", str(int(val))]
        out = []
        for st in steps:
            if not out or out[-1] != st:
                out.append(st)
        calc += f"<div class='xc'><span class='muted'>{m('x=' + str(x))} रखने पर,</span>" + lines("y", *out) + "</div>"
    head = f"<div class='vt'>{name} से " + m("y=" + ytex) + "</div>"
    return head + "<div class='xcs'>" + calc + "</div>" + vtable("सारणी:", xs, ys)


def sq(label, *items):
    """A sub-question on its own line; several equations stacked one below the other."""
    body = "<br>".join(items)
    return f"<div class='sq'><span class='sl'>{label}</span><span class='stk'>{body}</span></div>"


def graph(lns, xr, yr, pts, step=1, shade=None, label="आलेख"):
    """lns: list of (a, b, c, colour, name) for ax+by+c=0; pts: list of (x, y, text)."""
    ux = 300 / (xr[1] - xr[0])
    W = 300 + 40
    H = int((yr[1] - yr[0]) * ux) + 40
    ox, oy = 20, 20
    sx = lambda x: ox + (x - xr[0]) * ux
    sy = lambda y: oy + (yr[1] - y) * ux
    g = []
    k = xr[0]
    while k <= xr[1]:
        g.append(f"<line x1='{sx(k):.1f}' y1='{sy(yr[0]):.1f}' x2='{sx(k):.1f}' y2='{sy(yr[1]):.1f}' stroke='#d6e6f7'/>")
        if k != 0 and k % step == 0:
            g.append(f"<text x='{sx(k):.1f}' y='{sy(0) + 13:.1f}' font-size='10' text-anchor='middle' fill='#555'>{int(k)}</text>")
        k += 1 if step == 1 else step / 2
    k = yr[0]
    while k <= yr[1]:
        g.append(f"<line x1='{sx(xr[0]):.1f}' y1='{sy(k):.1f}' x2='{sx(xr[1]):.1f}' y2='{sy(k):.1f}' stroke='#d6e6f7'/>")
        if k != 0 and k % step == 0:
            g.append(f"<text x='{sx(0) - 4:.1f}' y='{sy(k) + 4:.1f}' font-size='10' text-anchor='end' fill='#555'>{int(k)}</text>")
        k += 1 if step == 1 else step / 2
    mk = ("<defs><marker id='ar' viewBox='0 0 10 10' refX='8' refY='5' markerWidth='9' markerHeight='9' markerUnits='userSpaceOnUse' orient='auto-start-reverse'>"
          "<path d='M0,0 L10,5 L0,10 z' fill='#222'/></marker></defs>")
    ax = (f"<line x1='{sx(xr[0]):.1f}' y1='{sy(0):.1f}' x2='{sx(xr[1]):.1f}' y2='{sy(0):.1f}' stroke='#222' stroke-width='1.5' marker-start='url(#ar)' marker-end='url(#ar)'/>"
          f"<line x1='{sx(0):.1f}' y1='{sy(yr[0]):.1f}' x2='{sx(0):.1f}' y2='{sy(yr[1]):.1f}' stroke='#222' stroke-width='1.5' marker-start='url(#ar)' marker-end='url(#ar)'/>"
          f"<text x='{sx(xr[1]) + 2:.1f}' y='{sy(0) - 5:.1f}' font-size='12' font-weight='700'>X</text>"
          f"<text x='{sx(xr[0]) - 6:.1f}' y='{sy(0) - 5:.1f}' font-size='12' font-weight='700'>X′</text>"
          f"<text x='{sx(0) + 5:.1f}' y='{sy(yr[1]) + 4:.1f}' font-size='12' font-weight='700'>Y</text>"
          f"<text x='{sx(0) + 5:.1f}' y='{sy(yr[0]) + 4:.1f}' font-size='12' font-weight='700'>Y′</text>"
          f"<text x='{sx(0) - 11:.1f}' y='{sy(0) + 13:.1f}' font-size='11'>O</text>")
    sh = ""
    if shade:
        sh = "<polygon points='" + " ".join(f"{sx(x):.1f},{sy(y):.1f}" for x, y in shade) + "' fill='#f4b400' fill-opacity='.45' stroke='none'/>"
    L = []
    used = []
    for i, (a, b, c, col, nm) in enumerate(lns):
        seg = []
        n = 2000
        for j in range(n + 1):
            x = xr[0] + (xr[1] - xr[0]) * j / n
            y = (-c - a * x) / b
            if yr[0] <= y <= yr[1]:
                seg.append((x, y))
        (x1, y1), (x2, y2) = seg[0], seg[-1]
        dash = " stroke-dasharray='7 5'" if i == 1 and len(lns) == 2 and abs(a * lns[0][1] - b * lns[0][0]) < 1e-9 and abs(a * lns[0][2] - c * lns[0][0]) < 1e-9 else ""
        L.append(f"<line x1='{sx(x1):.1f}' y1='{sy(y1):.1f}' x2='{sx(x2):.1f}' y2='{sy(y2):.1f}' stroke='{col}' stroke-width='{2.4 if not dash else 3.2}'{dash}/>")
        best = None
        for fpos in (0.1, 0.9, 0.22, 0.78, 0.35, 0.65, 0.5):
            tx, ty = seg[min(len(seg) - 1, int(len(seg) * fpos))]
            cx, cy = sx(tx) + 6, sy(ty) - 6
            dmin = min([((cx + 25 - sx(x)) ** 2 + (cy - sy(y) + 4) ** 2) ** .5 for x, y, _ in pts] + [((cx - qx) ** 2 + (cy - qy) ** 2) ** .5 for qx, qy in used] + [999])
