def frac_tex(fr):
    fr = F(fr)
    if fr.denominator == 1:
        return str(fr.numerator)
    s = "-" if fr < 0 else ""
    return f"{s}\\dfrac{{{abs(fr.numerator)}}}{{{fr.denominator}}}"


def coeff_tex(v):
    v = F(v)
    return frac_tex(v)


def ratios(c1, c2, show_c=True):
    """c1, c2: (a,b,c) as Fractions in form ax+by+c=0. Returns HTML with coefficient table and the three ratios."""
    a1, b1, k1 = map(F, c1)
    a2, b2, k2 = map(F, c2)
    t = ("<table class='rt'><tr><th></th><th>" + m("a") + "</th><th>" + m("b") + "</th><th>" + m("c") + "</th></tr>"
         f"<tr><th>पहला समीकरण</th><td>{m('a_1=' + coeff_tex(a1))}</td><td>{m('b_1=' + coeff_tex(b1))}</td><td>{m('c_1=' + coeff_tex(k1))}</td></tr>"
         f"<tr><th>दूसरा समीकरण</th><td>{m('a_2=' + coeff_tex(a2))}</td><td>{m('b_2=' + coeff_tex(b2))}</td><td>{m('c_2=' + coeff_tex(k2))}</td></tr></table>")

    def one(sym, x, y):
        x, y = F(x), F(y)
        raw = f"\\dfrac{{{coeff_tex(x)}}}{{{coeff_tex(y)}}}"
        val = frac_tex(x / y)
        steps = [raw]
        if x.denominator != 1 or y.denominator != 1:
            ry = f"\\dfrac{{1}}{{{abs(y)}}}" if y.denominator == 1 else f"\\dfrac{{{y.denominator}}}{{{abs(y.numerator)}}}"
            ry = ry if y > 0 else f"\\left(-{ry}\\right)"
            steps.append(f"{coeff_tex(x)}\\times {ry}")
        if steps[-1] != val:
            steps.append(val)
        return lines(f"\\dfrac{{{sym}_1}}{{{sym}_2}}", *steps), x / y

    h1, r1 = one("a", a1, a2)
    h2, r2 = one("b", b1, b2)
    out = t + h1 + h2
    r3 = None
    if show_c:
        h3, r3 = one("c", k1, k2)
        out += h3
    return out, r1, r2, r3


def sym(r1, r2, r3=None):
    s = lambda x, y: "=" if x == y else "\\ne"
    if r3 is None:
        return m(f"\\dfrac{{a_1}}{{a_2}}{s(r1, r2)}\\dfrac{{b_1}}{{b_2}}")
    return m(f"\\dfrac{{a_1}}{{a_2}}{s(r1, r2)}\\dfrac{{b_1}}{{b_2}}{s(r2, r3)}\\dfrac{{c_1}}{{c_2}}")


