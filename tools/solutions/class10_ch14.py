def tab(head, rows, hl=None, wrap=None, lb=False):
    h = "".join(f"<th>{c}</th>" for c in head) if head else ""
    body = ""
    for i, r in enumerate(rows):
        cls = " class='hl'" if hl is not None and i in hl else ""
        cells = ""
        for j, c in enumerate(r):
            cc = " class='wr'" if wrap is not None and j == wrap else (" class='lb'" if lb and j == 0 else "")
            cells += f"<td{cc}>{c}</td>"
        body += f"<tr{cls}>{cells}</tr>"
    th = f"<thead><tr>{h}</tr></thead>" if head else ""
    return f"<div class='tw'><table class='st'>{th}<tbody>{body}</tbody></table></div>"


